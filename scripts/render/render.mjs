#!/usr/bin/env node
/**
 * Renders every image in scripts/render/shots.mjs from public/models/*.glb in
 * headless Chromium (three.js from node_modules), then encodes responsive
 * AVIF + WebP sets into public/renders/ and writes the typed manifest
 * src/content/renders.ts. og-image.jpg (1200×630) is written as JPEG.
 *
 *   NODE_PATH=$(npm root -g) npm run model:render
 *   … -- --only=hero        render a subset (regex on keys), keeps the rest of the manifest
 *   … -- --preview=DIR      write quick PNG previews (40 % size) to DIR, nothing else
 */
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { ROOT, openHarness, renderPNG, startBrowser, startServer } from "./harness.mjs";
import { SIZES, buildShots } from "./shots.mjs";

const OUT = path.join(ROOT, "public/renders");
const MANIFEST = path.join(ROOT, "src/content/renders.ts");

const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, v] = a.replace(/^--/, "").split("=");
    return [k, v ?? true];
  }),
);

/** Read the bits of copy the renders need straight from src/content (no TS runtime needed). */
async function readContent() {
  const build = await fs.readFile(path.join(ROOT, "src/content/build.ts"), "utf8");
  const buildSteps = [...build.matchAll(/\n {4}id: "([^"]+)",[\s\S]*?renderAlt: "([^"]+)"/g)].map((m) => ({ id: m[1], renderAlt: m[2] }));
  const permitsSrc = await fs.readFile(path.join(ROOT, "src/content/permits.ts"), "utf8");
  const permits = [...permitsSrc.matchAll(/id: "([^"]+)",[\s\S]*?diagramAlt: "([^"]+)"/g)].map((m) => ({ id: m[1], diagramAlt: m[2] }));
  const site = await fs.readFile(path.join(ROOT, "src/content/site.ts"), "utf8");
  const heroAlt = (site.match(/posterAlt:\s*"([^"]+)"/) || [])[1] || "3D-gjengivelse av huset i blå time.";
  if (buildSteps.length !== 11) throw new Error(`Expected 11 build steps in src/content/build.ts, found ${buildSteps.length}`);
  if (permits.length !== 5) throw new Error(`Expected 5 permit types, found ${permits.length}`);
  return { buildSteps, permits, heroAlt };
}

async function encode(key, png, size) {
  const img = sharp(png);
  const sources = { avif: [], webp: [] };
  if (size.jpg) {
    const file = path.join(OUT, `${key}.jpg`);
    await img.resize(size.w, size.h, { kernel: "lanczos3" }).jpeg({ quality: 84, mozjpeg: true }).toFile(file);
    return { jpg: `/renders/${key}.jpg` };
  }
  for (const w of size.avif) {
    const file = `${key}-${w}.avif`;
    await sharp(png).resize(w, null, { kernel: "lanczos3" }).avif({ quality: w >= 1600 ? 50 : 54, effort: 6, chromaSubsampling: "4:2:0" }).toFile(path.join(OUT, file));
    sources.avif.push({ src: `/renders/${file}`, w });
  }
  for (const w of size.webp) {
    const file = `${key}-${w}.webp`;
    await sharp(png).resize(w, null, { kernel: "lanczos3" }).webp({ quality: 72, effort: 6, smartSubsample: true }).toFile(path.join(OUT, file));
    sources.webp.push({ src: `/renders/${file}`, w });
  }
  const tiny = await sharp(png).resize(20, null).blur(0.6).webp({ quality: 40 }).toBuffer();
  return { sources, placeholder: `data:image/webp;base64,${tiny.toString("base64")}` };
}

function ts(str) {
  return JSON.stringify(str);
}

async function writeManifest(entries) {
  const keys = Object.keys(entries).sort();
  const body = keys
    .map((k) => {
      const e = entries[k];
      const src = (list) => list.map((s) => `{ src: ${ts(s.src)}, w: ${s.w} }`).join(", ");
      return `  ${ts(k)}: {
    alt: ${ts(e.alt)},
    width: ${e.width},
    height: ${e.height},
    sources: {
      avif: [${src(e.sources.avif)}],
      webp: [${src(e.sources.webp)}],
    },
    placeholder: ${ts(e.placeholder)},
  },`;
    })
    .join("\n");
  const file = `/**
 * GENERATED by scripts/render/render.mjs (npm run model:render) — do not edit.
 * Renders of our own 3D model of the reference house (our interpretation of
 * "House in Bergen" by Kvalbein Korsøen Arkitektur, not built by Bygg RV)
 * and of the permit diagrams. Render with <Picture asset={renders[key]} />.
 */
import type { RenderAsset, RenderManifest } from "@/lib/images";

export const renders: RenderManifest = {
${body}
};

export type RenderKey = ${keys.map(ts).join(" | ")};

export function getRender(key: string): RenderAsset | null {
  return renders[key] ?? null;
}

/** Open Graph image (1200×630 JPEG), referenced from src/lib/seo.ts. */
export const ogImagePath = "/renders/og-image.jpg";
`;
  await fs.writeFile(MANIFEST, file);
}

/** Parse the existing generated manifest (to keep entries during --only runs). */
async function readExistingManifest() {
  try {
    const src = await fs.readFile(MANIFEST, "utf8");
    if (!src.includes("GENERATED by scripts/render/render.mjs")) return {};
    const m = src.match(/export const renders: RenderManifest = (\{[\s\S]*?\n\});/);
    if (!m) return {};
    // the object literal is JSON-compatible apart from unquoted property names and trailing commas
    const json = m[1]
      .replace(/(\s)(alt|width|height|sources|avif|webp|placeholder|src|w):/g, '$1"$2":')
      .replace(/,(\s*[}\]])/g, "$1");
    return JSON.parse(json);
  } catch {
    return {};
  }
}

async function main() {
  const content = await readContent();
  let shots = buildShots(content);
  if (args.only) {
    const re = new RegExp(args.only);
    shots = shots.filter((s) => re.test(s.key));
  }
  const preview = typeof args.preview === "string" ? path.resolve(args.preview) : null;
  if (preview) await fs.mkdir(preview, { recursive: true });
  else await fs.mkdir(OUT, { recursive: true });

  const { server, url } = await startServer();
  const browser = await startBrowser();
  const entries = args.only && !preview ? await readExistingManifest() : {};
  const t0 = Date.now();
  try {
    const page = await openHarness(browser, url);
    for (const shot of shots) {
      const size = SIZES[shot.size];
      const scale = preview ? 0.4 : size.ss;
      const t = Date.now();
      const png = await renderPNG(page, { ...shot, width: Math.round(size.w * scale), height: Math.round(size.h * scale) });
      if (preview) {
        await fs.writeFile(path.join(preview, `${shot.key}.png`), png);
      } else {
        const enc = await encode(shot.key, png, size);
        if (!size.jpg) entries[shot.key] = { alt: shot.alt, width: size.w, height: size.h, ...enc };
      }
      console.log(`${shot.key.padEnd(34)} ${((Date.now() - t) / 1000).toFixed(1)} s`);
    }
  } finally {
    await browser.close();
    server.close();
  }
  if (!preview) {
    await writeManifest(entries);
    if (!args.only) {
      // remove stale files that are no longer in the manifest
      const keep = new Set(Object.values(entries).flatMap((e) => [...e.sources.avif, ...e.sources.webp].map((s) => path.basename(s.src))));
      keep.add("og-image.jpg");
      for (const f of await fs.readdir(OUT)) if (!keep.has(f)) await fs.rm(path.join(OUT, f));
    }
    let total = 0;
    for (const f of await fs.readdir(OUT)) total += (await fs.stat(path.join(OUT, f))).size;
    console.log(`public/renders: ${(await fs.readdir(OUT)).length} files, ${(total / 1024 / 1024).toFixed(2)} MB`);
  }
  console.log(`done in ${((Date.now() - t0) / 60000).toFixed(1)} min`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
